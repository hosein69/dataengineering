def status_of(value) -> Status:
    """(رنگ، آیکن، برچسب) برای یک کد یا برچسب وضعیت؛ نامشخص را هم بی‌خطا برمی‌گرداند."""
    s = str(value or "").strip()
    if s in STATUS:
        return STATUS[s]
    if s in STATUS_BY_LABEL:
        return STATUS_BY_LABEL[s]
    return STATUS["unknown"]
