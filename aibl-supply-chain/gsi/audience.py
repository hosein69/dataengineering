# -*- coding: utf-8 -*-
"""مخاطب گزارش — یک گزارش، سه خواننده، سه نیاز متفاوت.

## مسئله‌ای که این ماژول حل می‌کند

تا اینجا GSI یک خروجی می‌ساخت و همه آن را می‌گرفتند. نتیجه این بود که هیچ‌کس
خروجی را «مال خودش» نمی‌دانست:

* **کارشناس** باید فردا صبح بداند کدام پرونده را دست بگیرد. ستون «تکمیل
  فرآیند (٪)» و «امتیاز انطباق» هیچ کمکی به او نمی‌کند؛ او شماره پرونده،
  مانع، و تماس بعدی را می‌خواهد.
* **مدیر میانی** پرونده جداگانه را دنبال نمی‌کند. او می‌خواهد بداند صف کجا
  جمع شده، کدام مرحله کند شده و ظرفیت تیمش کجا صرف می‌شود.
* **مدیر ارشد** نه صف می‌خواهد نه پرونده. او سه تا پنج تصمیم می‌خواهد، با
  مبلغ و ریسک، و اینکه اگر امروز تصمیم نگیرد چه چیزی از دست می‌رود.

وقتی هر سه یک فایل می‌گیرند، کارشناس در انبوه نمودار گم می‌شود و مدیر ارشد
در انبوه ردیف. هیچ‌کدام گزارش را باز نمی‌کنند و سیستم — با وجود درست بودن —
بی‌اثر می‌ماند.

## قاعده‌ای که این ماژول را از «تم» جدا می‌کند

پروفایل مخاطب **محتوا** را عوض می‌کند، نه رنگ را. سیستم طراحی یکی است؛
آنچه تغییر می‌کند این است که چه چیزی نشان داده شود، به چه ترتیبی، با چه
عمقی، و چه چیزی **نشان داده نشود**.

## چه چیزی عمداً از HTML بیرون ماند

سنجه‌های سلامت داده — درصد صحت، پوشش اسکیما، شکاف ادغام، امتیاز انطباق —
در هیچ پروفایل HTML نمی‌آیند. نه چون بی‌اهمیت‌اند؛ دقیقاً چون مهم‌اند و
مخاطبشان کس دیگری است. مدیری که «پوشش داده ۷۲٪» می‌بیند، به کل گزارش
بی‌اعتماد می‌شود بدون آنکه بتواند کاری بکند. این اعداد جای خودشان را دارند:
داشبورد Streamlit و شیت «سلامت سیستم» — جایی که کسی می‌نشیند که می‌تواند
دربارهٔ آنها **کاری** بکند.

اعتماد از پنهان‌کاری نمی‌آید؛ از این می‌آید که هر عدد، مخاطب درست خودش را
پیدا کند.
"""
from __future__ import annotations

__contract__ = 1

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple

#: شناسه پروفایل‌ها — در محیط با ``GSI_AUDIENCE`` انتخاب می‌شود.
EXPERT = "expert"
MANAGER = "manager"
EXECUTIVE = "executive"
ANALYST = "analyst"

#: متغیر محیطی انتخاب پروفایل پیش‌فرض.
AUDIENCE_ENV = "GSI_AUDIENCE"


@dataclass(frozen=True)
class Audience:
    """یک پروفایل مخاطب.

    هر فیلد یک تصمیم صریح است دربارهٔ اینکه این خواننده چه می‌بیند. هیچ
    چیزی «به‌طور پیش‌فرض» نمایش داده نمی‌شود — اگر در فهرست نیست، نمی‌آید.
    """

    key: str
    fa: str
    who: str                       # این پروفایل برای چه کسی است
    question: str                  # پرسشی که این خواننده صبح می‌پرسد

    #: بخش‌هایی که این خواننده می‌بیند.
    #:
    #: نام‌ها عمداً با نواحی **واقعی** صفحه یکی‌اند، نه مفاهیم انتزاعی:
    #: ``story`` روایت · ``process`` صف و گلوگاه · ``variants`` مسیرها ·
    #: ``factors`` عوامل همراه · ``fx`` جریان پول · ``warehouse`` اظهار
    #: انبار · ``table`` جدول ردیف‌ها · ``quality`` سلامت داده.
    #: اگر نامی اینجا نباشد، آن ناحیه برای این خواننده رندر نمی‌شود.
    sections: Tuple[str, ...]

    #: حداکثر یافته در «مسیر تصمیم». بیش از این، تصمیم رقیق می‌شود.
    max_findings: int
    #: حداکثر ردیف جدول پیش از صفحه‌بندی.
    table_rows: int
    #: عمق روایت: ۱ = یک جمله، ۲ = جمله + چرا، ۳ = جمله + چرا + شاهد.
    narrative_depth: int
    #: سنجه‌ها به ترتیب اهمیت برای این خواننده.
    kpis: Tuple[str, ...]
    #: نمودارها. فهرست خالی یعنی این خواننده نمودار نمی‌خواهد.
    charts: Tuple[str, ...]
    #: ستون‌های جدول اصلی.
    columns: Tuple[str, ...]
    #: آیا سنجه‌های کیفیت داده دیده شوند؟ فقط در محیط تحلیلی درست است.
    show_data_quality: bool = False
    #: آیا جزئیات فنی (گرین، مبنای محاسبه، شناسه رویداد) دیده شود؟
    show_provenance: bool = False
    #: پیشوند موضوع ایمیل.
    subject: str = "GSI"
    #: یادداشت پایانی — لحن همین‌جا تنظیم می‌شود.
    closing: str = ""


#: ── کارشناس ────────────────────────────────────────────────────────────
#: کسی که فردا صبح باید کاری بکند. تمرکز: پرونده، مانع، تماس بعدی.
#: نمودار کم، جدول بلند. هیچ سنجهٔ تجمیعی سازمانی نمی‌بیند چون کاری با آن
#: ندارد — و دیدنش فقط حس «این گزارش مال من نیست» می‌سازد.
_EXPERT = Audience(
    key=EXPERT,
    fa="کارشناس",
    who="کسی که پرونده را دست می‌گیرد و تماس بعدی را می‌گیرد",
    question="امروز کدام پرونده را دست بگیرم و مانعش چیست؟",
    sections=("story", "warehouse", "table"),
    max_findings=5,
    table_rows=200,
    narrative_depth=3,
    kpis=("پرونده‌های من", "منتظر اقدام من", "مهلت این هفته", "بیشترین انتظار"),
    charts=("low_resistance", "criticality"),
    columns=("CANONICAL_ORDER", "CANONICAL_BL", "KEY_MATERIAL", "وضعیت اظهار انبار",
             "بحرانی (کوتاه)", "مقاومت (روز)", "انتظار جاری (روز)", "مانع فعلی"),
    show_provenance=True,
    subject="GSI · کار امروز",
    closing="اگر عددی با آنچه می‌دانید نمی‌خواند، همان را بگویید — داده از فایل "
            "منبع می‌آید و اصلاحش سریع است.",
)

#: ── مدیر میانی ─────────────────────────────────────────────────────────
#: کسی که ظرفیت تیم را تخصیص می‌دهد. تمرکز: صف، انتظار، توزیع بار.
#: پرونده تک‌تک را نمی‌بیند مگر آنکه خودش باز کند.
_MANAGER = Audience(
    key=MANAGER,
    fa="مدیر میانی",
    who="کسی که ظرفیت تیم را تخصیص می‌دهد و گلوگاه را باز می‌کند",
    question="صف کجا جمع شده و ظرفیت تیمم کجا صرف می‌شود؟",
    sections=("story", "process", "variants", "fx", "warehouse", "table"),
    max_findings=4,
    table_rows=80,
    narrative_depth=2,
    kpis=("پرونده باز", "بزرگ‌ترین صف", "میانه انتظار", "بیشترین انتظار",
          "مهلت این هفته"),
    charts=("stage_queue", "org_workload", "low_resistance", "risk_mix"),
    columns=("CANONICAL_ORDER", "ORG_DEPT", "CANONICAL_EXPERT", "مرحله جاری",
             "انتظار جاری (روز)", "بحرانی (کوتاه)", "مانع فعلی"),
    subject="GSI · وضعیت صف و گلوگاه",
    closing="این نما وضعیت امروز است؛ برای دیدن سیر زمانی، داشبورد را باز کنید.",
)

#: ── مدیر ارشد ──────────────────────────────────────────────────────────
#: کسی که تصمیم می‌گیرد، نه کسی که پیگیری می‌کند. تمرکز: سه تصمیم، مبلغ،
#: و هزینهٔ تصمیم‌نگرفتن. جدول کوتاه، فقط برای اینکه بداند حرف از کجا آمده.
_EXECUTIVE = Audience(
    key=EXECUTIVE,
    fa="مدیر ارشد",
    who="کسی که تصمیم می‌گیرد و منابع را جابه‌جا می‌کند",
    question="امروز چه تصمیمی از من خواسته می‌شود و اگر نگیرم چه می‌شود؟",
    # جدول کوتاه عمداً می‌ماند: تصمیم‌گیرنده باید بتواند بپرسد «این عدد
    # از کجا آمد» و همان‌جا ده ردیف اولش را ببیند. حذف کامل جدول، گزارش را
    # به یک ادعای بی‌پشتوانه تبدیل می‌کند.
    sections=("story", "fx", "table"),
    max_findings=3,
    table_rows=10,
    narrative_depth=1,
    kpis=("ریسک توقف خط", "مبلغ در معرض ریسک", "مهلت عبورکرده", "پرونده باز"),
    charts=("risk_mix",),
    columns=("موضوع تصمیم", "اثر", "مالک", "مهلت"),
    subject="GSI · تصمیم‌های امروز",
    closing="هر سطر بالا یک تصمیم است؛ جزئیات پشت هرکدام نزد مالک همان سطر است.",
)

#: ── تحلیل‌گر ────────────────────────────────────────────────────────────
#: پروفایل داشبورد Streamlit. **تنها** جایی که کیفیت داده و مبنای محاسبه
#: دیده می‌شود، چون تنها جایی است که کسی می‌تواند دربارهٔ آن کاری بکند.
_ANALYST = Audience(
    key=ANALYST,
    fa="تحلیل‌گر داده",
    who="کسی که خود سیستم را نگه می‌دارد و کیفیت داده را می‌سنجد",
    question="کدام عدد قابل اتکاست و کجا داده کم داریم؟",
    sections=("story", "process", "variants", "factors", "fx",
              "warehouse", "table", "quality"),
    max_findings=8,
    table_rows=1000,
    narrative_depth=3,
    kpis=("پوشش داده", "پرونده بدون شاهد", "ردیف تکراری ادغام‌شده",
          "قاعده نزدیک انقضا", "پرونده باز"),
    charts=("stage_queue", "org_workload", "risk_mix", "low_resistance",
            "criticality", "stock_vs_total"),
    columns=("CANONICAL_ORDER", "CASE_KEY_BASIS", "رویداد یکتا",
             "نقاط کنترل طی‌شده (٪)", "انحراف فرآیند", "پایه انطباق",
             "عوامل همراه با انحراف"),
    show_data_quality=True,
    show_provenance=True,
    subject="GSI · نمای تحلیلی",
    closing="",
)

PROFILES: Dict[str, Audience] = {
    EXPERT: _EXPERT, MANAGER: _MANAGER,
    EXECUTIVE: _EXECUTIVE, ANALYST: _ANALYST,
}

#: ترتیب نمایش در رابط انتخاب — از نزدیک‌ترین به کار روزمره.
ORDER: Tuple[str, ...] = (EXPERT, MANAGER, EXECUTIVE, ANALYST)

#: پروفایل پیش‌فرض خروجی HTML. کارشناس، چون پرتعدادترین خواننده است و
#: گزارشی که برای او کار نکند، اصلاً باز نمی‌شود.
DEFAULT = EXPERT


def get(key: Optional[str] = None) -> Audience:
    """پروفایل مخاطب؛ با نام، با متغیر محیطی، یا پیش‌فرض."""
    import os
    name = (key or os.environ.get(AUDIENCE_ENV) or DEFAULT).strip().lower()
    return PROFILES.get(name, PROFILES[DEFAULT])


def choices() -> List[Tuple[str, str]]:
    """``[(کلید، برچسب فارسی)]`` برای منوی انتخاب."""
    return [(k, PROFILES[k].fa) for k in ORDER]


def allows(aud: Audience, section: str) -> bool:
    """آیا این بخش برای این مخاطب نمایش داده می‌شود؟"""
    return section in aud.sections
