# -*- coding: utf-8 -*-
"""لحن گزارش — قواعدی که اعتماد می‌سازند یا از بین می‌برند.

## چرا یک ماژول برای لحن

یک گزارش تحلیلی دو بار رد می‌شود: یک بار وقتی عددش غلط است، و یک بار وقتی
عددش درست است ولی خواننده حس می‌کند دارند او را بازی می‌دهند. دومی بی‌صداتر
و کشنده‌تر است، چون کسی دربارهٔ آن شکایت نمی‌کند — فقط دیگر فایل را باز
نمی‌کند.

این ماژول شش قاعده را در کد می‌گذارد تا هر متنی که تولید می‌شود از یک صافی
رد شود.

## شش قاعده

**۱) عدد بدون مخرج، حرف است.** «۱۴۷ قلم بحرانی» تا وقتی «از ۱٬۲۰۴» را
نبینیم، نه بزرگ است نه کوچک. هر ادعای کمی مخرج خودش را حمل می‌کند.

**۲) بزرگ‌نمایی، یک بار جواب می‌دهد.** «بحران»، «فاجعه»، «فوری!!!» در
نوبت اول توجه می‌گیرد و در نوبت سوم بی‌اثر می‌شود؛ بعد از آن حتی هشدار
واقعی هم خوانده نمی‌شود. شدت از **عدد** می‌آید، نه از صفت.

**۳) مانع، نه مقصر.** «تأخیر به‌خاطر کارشناس فلانی» یک اتهام است و پاسخش
دفاع است، نه اقدام. «این پرونده منتظر تأیید مالی است، ۱۹ روز» یک واقعیت
است که می‌شود دربارهٔ آن کاری کرد. آدم‌ها با اسم در گزارش می‌آیند فقط
به‌عنوان **مالک اقدام بعدی**، نه به‌عنوان علت گذشته.

**۴) ندانستن را بگو.** «شاهد کافی نداریم» یک جملهٔ کامل است. سیستمی که
نبودِ داده را با «۱۰۰٪ سالم» پر می‌کند، اولین باری که کسی متوجه شود، کل
اعتبارش را می‌بازد.

**۵) همبستگی را علت ننام.** «گروه X نرخ انحراف بالاتری دارد» درست است؛
«علت مشکل، X است» ادعایی است که داده‌اش را نداریم.

**۶) هر جمله به یک اقدام ختم شود.** مشاهده‌ای که اقدام ندارد، یادداشت است
نه یافته. اگر اقدامی نیست، آن سطر جای دیگری دارد.

## آنچه این ماژول **نمی‌کند**

متن را «مثبت» نمی‌کند. خبر بد، بد گفته می‌شود — فقط دقیق و بدون صفت. هدف
جلب اعتماد است، نه جلب رضایت.
"""
from __future__ import annotations

__contract__ = 1

import re
from typing import Iterable, List, Optional, Sequence

#: کلماتی که شدت را از عدد نمی‌گیرند و باید جایگزین شوند.
#: کلید = الگو، مقدار = جایگزین خنثی‌تر.
HYPE = {
    "فاجعه": "وضعیت بحرانی",
    "فاجعه‌بار": "بحرانی",
    "وحشتناک": "بحرانی",
    "بی‌سابقه": "بالاترین مقدار ثبت‌شده",
    "هشدار جدی": "هشدار",
    "فوراً": "در اولویت امروز",
    "قطعاً": "بر پایه داده موجود",
    "بدون شک": "بر پایه داده موجود",
    "همه": "همهٔ موارد بررسی‌شده",
}

#: عبارت‌هایی که علت را ادعا می‌کنند در حالی که فقط همبستگی داریم.
CAUSAL = {
    "علت اصلی": "عامل همراه",
    "علت ریشه‌ای": "عامل همراه با انحراف",
    "به‌خاطر": "همراه با",
    "ناشی از": "همراه با",
    "باعث شده": "با آن همبسته است",
}

#: واژگان «مانع» به‌جای «مقصر».
BLAME = {
    "مقصر": "مانع فعلی",
    "قصور": "توقف",
    "کوتاهی": "تأخیر",
    "اهمال": "تأخیر",
}

#: چهار حالتی که هرگز نباید در هم ادغام شوند.
#: نسخه‌های قبلی این پکیج هر چهار را به «۰» یا «۱۰۰٪» تبدیل می‌کردند.
UNKNOWN = "نامشخص"
NOT_YET = "هنوز انجام نشده"
NOT_APPLICABLE = "موضوعیت ندارد"
NO_EVIDENCE = "شاهد کافی نداریم"

STATES = (UNKNOWN, NOT_YET, NOT_APPLICABLE, NO_EVIDENCE)


def plain(text: str) -> str:
    """صافیِ لحن: بزرگ‌نمایی، ادعای علّی و واژگان اتهامی را خنثی می‌کند.

    عمداً ساده است. کار این تابع گرفتنِ اشتباه‌های آشکار است، نه ویرایش
    ادبی؛ متن خوب همچنان باید خوب نوشته شود.
    """
    out = str(text or "")
    for table in (HYPE, CAUSAL, BLAME):
        for bad, good in table.items():
            out = re.sub(rf"(?<![\w‌]){re.escape(bad)}(?![\w‌])", good, out)
    out = re.sub(r"[!؟]{2,}", "!", out)          # !!! → !
    return re.sub(r"\s{2,}", " ", out).strip()


def quantify(value, total=None, unit: str = "", *, of: str = "از") -> str:
    """عدد با مخرجش — قاعده یک.

    >>> quantify(147, 1204, "قلم")
    '۱۴۷ قلم از ۱٬۲۰۴'
    """
    if value is None or value == "":
        return UNKNOWN
    head = f"{fa_num(value)}{(' ' + unit) if unit else ''}"
    if total in (None, "", 0):
        return head
    return f"{head} {of} {fa_num(total)}"


def share(part, total) -> str:
    """سهم، با مخرج — هرگز درصد تنها."""
    try:
        p, t = float(part), float(total)
    except (TypeError, ValueError):
        return UNKNOWN
    if t <= 0:
        return UNKNOWN
    return f"{fa_num(round(p / t * 100, 1))}٪ ({fa_num(part)} از {fa_num(total)})"


def evidence(n: Optional[int], *, what: str = "پرونده") -> str:
    """وزن شاهد را صریح می‌کند — قاعده چهار و پنج."""
    if not n:
        return f"({NO_EVIDENCE})"
    if n < 5:
        return f"(بر پایه فقط {fa_num(n)} {what} — برای نتیجه‌گیری کم است)"
    return f"(بر پایه {fa_num(n)} {what})"


def action(what: str, owner: str = "", due: str = "") -> str:
    """اقدام با مالک و مهلت — قاعده شش.

    اگر مالک یا مهلت نداریم، همان را می‌گوییم؛ جای خالی را با حدس پر
    نمی‌کنیم.
    """
    parts = [plain(what)]
    parts.append(f"مالک: {owner}" if owner else "مالک: تعیین نشده")
    parts.append(f"مهلت: {due}" if due else "مهلت: تعیین نشده")
    return " · ".join(parts)


def blocker(reason: str, days=None, waiting_on: str = "") -> str:
    """مانع، نه مقصر — قاعده سه."""
    s = plain(reason)
    if days not in (None, ""):
        s += f" — {fa_num(days)} روز"
    if waiting_on:
        s += f" · منتظر: {waiting_on}"
    return s


_FA_DIGITS = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")


def fa_num(v) -> str:
    """عدد با ارقام فارسی و جداکننده هزارگان."""
    if v is None or v == "":
        return UNKNOWN
    try:
        f = float(v)
    except (TypeError, ValueError):
        return str(v)
    s = f"{int(f):,}" if float(f).is_integer() else f"{f:,.1f}"
    # جداکننده هزارگان ٬ و اعشار ٫ — همان قراردادی که نمودارها و Excel دارند
    return s.replace(",", "٬").replace(".", "٫").translate(_FA_DIGITS)


def headline(count: int, total: int, subject: str, *,
             none_text: str = "") -> str:
    """تیتر — با مخرج، بدون صفت، و صادق وقتی چیزی نیست."""
    if not count:
        return plain(none_text or f"در این برش، {subject} دیده نشد.")
    return plain(f"{quantify(count, total, '')} {subject}")


def bullet(observation: str, comparison: str = "", size: str = "",
           confidence: str = "", act: str = "") -> str:
    """یک یافته کامل: مشاهده ← مقایسه ← اندازه ← اطمینان ← اقدام.

    اجزای خالی حذف می‌شوند، ولی ``act`` که نباشد، در انتها یادآوری می‌شود —
    چون یافتهٔ بدون اقدام، یافته نیست.
    """
    bits = [plain(observation)]
    for extra in (comparison, size, confidence):
        if extra:
            bits.append(plain(extra))
    bits.append(plain(act) if act else "اقدام: هنوز تعریف نشده")
    return " · ".join(bits)
