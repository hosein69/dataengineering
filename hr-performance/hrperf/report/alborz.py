def rgba(hex_color: str, alpha: float) -> str:
    """``#RRGGBB`` + شفافیت → ``rgba(...)``.

    بدون این، هر جا شفافیت لازم می‌شد یک رشتهٔ ``rgba`` دستی نوشته
    می‌شد و رنگ از منبع واحد بیرون می‌زد.
    """
    h = hex_color.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    return f"rgba({r},{g},{b},{alpha})"


