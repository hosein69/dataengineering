def shadow_css() -> str:
    """همان دو لایهٔ سایه، برای CSS."""
    r, g, b = (int(v * 255) for v in SHADOW_RGB)
    near = f"0 {SHADOW_NEAR[0]}px {SHADOW_NEAR[1]}px {SHADOW_NEAR[2]}px rgba({r},{g},{b},{SHADOW_NEAR[3]})"
